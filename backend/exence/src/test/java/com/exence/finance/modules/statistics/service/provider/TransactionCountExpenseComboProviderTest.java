package com.exence.finance.modules.statistics.service.provider;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.BDDMockito.given;

import com.exence.finance.common.i18n.I18nService;
import com.exence.finance.modules.statistics.dto.StatisticsWidgetType;
import com.exence.finance.modules.statistics.dto.Timeframe;
import com.exence.finance.modules.statistics.dto.WidgetRequest;
import com.exence.finance.modules.statistics.dto.payload.SeriesPayload;
import com.exence.finance.modules.statistics.repository.StatisticsQueryService;
import com.exence.finance.modules.statistics.service.StatisticsFilterFactory;
import java.time.LocalDate;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.Spy;
import org.mockito.junit.jupiter.MockitoExtension;

@ExtendWith(MockitoExtension.class)
class TransactionCountExpenseComboProviderTest {

    @Mock
    private I18nService i18n;

    @Mock
    private StatisticsQueryService statisticsQueryService;

    @Mock
    private ProviderHelper providerHelper;

    @Spy
    private StatisticsFilterFactory filterFactory;

    @InjectMocks
    private TransactionCountExpenseComboProvider provider;

    @Test
    @DisplayName("returns TRANSACTION_COUNT_EXPENSE_COMBO as the supported widget type")
    void getSupportedType_returnsTransactionCountExpenseCombo() {
        assertThat(provider.getSupportedType()).isEqualTo(StatisticsWidgetType.TRANSACTION_COUNT_EXPENSE_COMBO);
    }

    @Test
    @DisplayName("returns two series with data points for the given time range")
    void getData_withResults() {
        // given
        WidgetRequest request =
                new WidgetRequest(LocalDate.of(2025, 1, 1), LocalDate.of(2025, 1, 31), Timeframe.ONE_MONTH, Map.of());
        given(statisticsQueryService.findMonthlyIncomeExpense(any())).willReturn(List.of());
        given(providerHelper.findByMonth(any(), any())).willReturn(Optional.empty());
        given(i18n.get("label.expense")).willReturn("Expense");
        given(i18n.get("label.transaction-count")).willReturn("Count");

        // when
        SeriesPayload result = (SeriesPayload) provider.getData(request);

        // then
        assertThat(result.type()).isEqualTo(StatisticsWidgetType.TRANSACTION_COUNT_EXPENSE_COMBO);
        assertThat(result.series()).hasSize(2);
    }
}
